import unittest

from physikmdb import PhysikMDBError

from kmap.library.database import cache_name, is_database_url
from kmap.library.orbitaldata import OrbitalData
from kmap import __directory__


class TestOrbitalData(unittest.TestCase):
    def test_default_initialization(self):
        name = "Test"
        ID = 1
        meta_data = {"origin": "selfmade"}
        with open(__directory__ / "../example/data/5A_MO_73.cube", "r") as f:
            file = f.read()

        data = OrbitalData(file, ID, name=name, meta_data=meta_data)

        self.assertEqual(data.name, name)
        self.assertEqual(data.ID, ID)
        self.assertEqual(data.meta_data, meta_data)

    def test_file_initialization(self):
        ID = 1
        data = OrbitalData.init_from_file(
            __directory__ / "../example/data/" / "5A_MO_73.cube", ID
        )

        self.assertEqual(data.name, "5A_MO_73")
        self.assertEqual(data.ID, ID)
        self.assertEqual(
            data.meta_data,
            {"origin": "Cube file generated by NWChem", "alias": "pentacene_MO_73"},
        )

    def test_url_recognition(self):
        self.assertTrue(is_database_url("physikmdb://1/9"))
        self.assertTrue(
            is_database_url("http://physikmdb.uni-graz.at/cubefiles/000001/1P_MO_10")
        )
        self.assertFalse(is_database_url("http://example.com/some_orbital.cube"))

        self.assertEqual(cache_name("physikmdb://1/9"), "physikmdb_1_9")
        self.assertEqual(
            cache_name("http://physikmdb.uni-graz.at/cubefiles/000001/1P_MO_10"),
            "000001_1P_MO_10",
        )

    def test_online_initialization(self):
        # Calculation 1 is benzene, B3LYP/6-31G*; index 9 is its MO 10, the
        # orbital the old database served as cubefiles/000001/1P_MO_10.
        ID = 1
        URL = "physikmdb://1/9"
        try:
            data = OrbitalData.init_from_online(URL, ID)

        except PhysikMDBError:
            self.skipTest("The online database is not reachable.")

        self.assertEqual(data.name, "1P_MO_10")
        self.assertEqual(data.ID, ID)
        self.assertEqual(data.molecule["num_atom"], 12)
